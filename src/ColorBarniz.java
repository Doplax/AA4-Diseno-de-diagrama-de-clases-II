/**
 * Enumeración que representa los colores disponibles para los barnices en WoodShops.
 * <p>
 * Se utiliza en la clase {@link Barniz} para indicar el tono o acabado del barniz.
 * </p>
 *
 * @author Pol Valle Montes
 * @version 1.0
 */
public enum ColorBarniz {

    /** Barniz transparente, sin pigmentación de color. */
    INCOLORO,

    /** Barniz con tono caoba, de color marrón rojizo oscuro. */
    CAOBA,

    /** Barniz con tono nogal, de color marrón cálido medio. */
    NOGAL
}
