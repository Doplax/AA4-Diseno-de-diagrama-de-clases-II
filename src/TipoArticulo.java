/**
 * Enumeración que representa los tipos de artículos disponibles en WoodShops.
 * <p>
 * Se utiliza en la clase {@link Articulo} para clasificar el tipo de mueble
 * u objeto al que pertenece el artículo.
 * </p>
 *
 * @author Pol Valle Montes
 * @version 1.0
 */
public enum TipoArticulo {

    /** Artículo de tipo estantería. */
    ESTANTERIA,

    /** Artículo de tipo mesa. */
    MESA,

    /** Artículo de tipo silla. */
    SILLA,

    /** Artículo de tipo armario. */
    ARMARIO
}
