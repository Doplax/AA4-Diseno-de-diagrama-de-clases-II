/**
 * Enumeración que representa los tipos de tablero disponibles en WoodShops.
 * <p>
 * Se utiliza en la clase {@link Tablero} para clasificar el material del tablero.
 * </p>
 *
 * @author Pol Valle Montes
 * @version 1.0
 */
public enum TipoTablero {

    /** Tablero de aglomerado, compuesto de partículas de madera prensadas. */
    AGLOMERADO,

    /** Tablero contrachapado, formado por capas de madera encoladas. */
    CONTRACHAPADO,

    /** Tablero de fibra de densidad media (MDF). */
    MDF
}
